import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  assertDataUi, componentFile, componentGeneratedPaths, listComponents,
} from './components.mjs';
import strings from './i18n.mjs';
import { toTitle } from './names.mjs';
import { compileTailwind } from './tailwind.mjs';

export const GENERATED_HEADER = 'Generated by aem-kit from';

/**
 * Showcase page: a standalone page (no scripts.js) so aem.js does not decorate the samples
 * (it would turn loose <div>s into blocks and rewrite the class of lone links into "button").
 * @param {string} id
 * @param {string} snippet components/{id}/{id}.html
 * @param {object} text i18n strings
 * @returns {string}
 */
function showcasePage(id, snippet, text) {
  const title = text.componentTitle(toTitle(id));
  const body = snippet.trim().split('\n').map((line) => (line ? `      ${line}` : line)).join('\n');
  return `<!DOCTYPE html>
<!-- ${GENERATED_HEADER} components/${id}/${id}.html. Do not edit. -->
<html lang="${text.lang}">
  <head>
    <title>${title}</title>
    <meta name="description" content="${text.componentDescription(toTitle(id))}" />
    <link rel="canonical" href="https://localhost/drafts/components/${id}" />
    <meta name="viewport" content="width=device-width, initial-scale=1"/>
    <link rel="stylesheet" href="/styles/styles.css"/>
    <link rel="stylesheet" href="/drafts/components/${id}.css"/>
    <script type="module">
      import initComponents from '/scripts/ui.js';

      initComponents(document.querySelector('main'));
      window.addEventListener('load', () => {
        const fonts = document.createElement('link');
        fonts.rel = 'stylesheet';
        fonts.href = '/styles/fonts.css';
        document.head.append(fonts);
      });
    </script>
  </head>
  <body class="appear">
    <main>
      <h1>${title}</h1>
${body}
    </main>
  </body>
</html>
`;
}

/**
 * Builds the showcase of one component: drafts/components/{id}.html + .css.
 * @param {{ root: string, config: object }} ctx
 * @param {string} id
 * @returns {Promise<void>}
 */
export async function buildComponent({ root, config }, id) {
  const htmlPath = componentFile(root, id, 'html');
  const snippet = await readFile(htmlPath, 'utf8');
  assertDataUi(root, snippet, `components/${id}/${id}.html`);
  if (existsSync(componentFile(root, id, 'js')) && !snippet.includes(`data-ui="${id}"`)) {
    console.warn(`⚠ components/${id}/${id}.html: a vitrine não usa data-ui="${id}", então o ${id}.js não roda nela.`);
  }
  const dir = path.join(root, 'drafts', 'components');
  await mkdir(dir, { recursive: true });
  const [pagePath, cssPath] = componentGeneratedPaths(id).map((rel) => path.join(root, rel));
  const css = await compileTailwind({
    root, config, dir, sources: [htmlPath], output: cssPath,
  });
  await writeFile(cssPath, `/* ${GENERATED_HEADER} components/${id}/${id}.html. Do not edit. */\n/* stylelint-disable */\n${css}`);
  await writeFile(pagePath, showcasePage(id, snippet, strings(config.language)));
  console.log(`components/${id}: drafts/components/${id}.html, drafts/components/${id}.css`);
}

/**
 * Builds every component showcase.
 * @param {{ root: string, config: object }} ctx
 * @returns {Promise<string[]>} component ids
 */
export async function buildComponents(ctx) {
  const ids = await listComponents(ctx.root);
  await ids.reduce((queue, id) => queue.then(() => buildComponent(ctx, id)), Promise.resolve());
  return ids;
}
