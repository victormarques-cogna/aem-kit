import { readFileSync } from 'node:fs';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { componentStylesheets } from './components.mjs';
import { CONFIG_FILE } from './config.mjs';
import { run } from './project.mjs';
import { themeBlock, utilityOverrides } from './theme.mjs';

/**
 * @param {string} root
 * @returns {string} Tailwind CLI entry installed in the project
 */
function tailwindCli(root) {
  const require = createRequire(path.join(root, 'package.json'));
  const pkgPath = require.resolve('@tailwindcss/cli/package.json');
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const bin = typeof pkg.bin === 'string' ? pkg.bin : Object.values(pkg.bin)[0];
  return path.join(path.dirname(pkgPath), bin);
}

/**
 * @param {string} from directory
 * @param {string} to file
 * @returns {string} POSIX relative path (Tailwind @import/@source)
 */
function relative(from, to) {
  const rel = path.relative(from, to).split(path.sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

/**
 * Compiles the utilities used by `sources` with the project theme and every component's
 * classes (components/{id}/{id}.css), without preflight (styles/styles.css owns the reset).
 * @param {{ root: string, config: object, dir: string, sources: string[], output: string }} opts
 *   dir: where the temporary input file is written (relative imports resolve from it)
 * @returns {Promise<string>} minified CSS
 */
export async function compileTailwind({
  root, config, dir, sources, output,
}) {
  const imports = (await componentStylesheets(root)).map((file) => `@import "${relative(dir, file)}";\n`).join('');
  const input = path.join(dir, '_tailwind.input.css');
  await writeFile(input, `@layer theme, base, components, utilities;
@import "tailwindcss/theme.css" layer(theme) source(none);
@import "tailwindcss/utilities.css" layer(utilities) source(none);
${imports}${themeBlock(config)}${utilityOverrides()}${sources.map((file) => `@source "${relative(dir, file)}";\n`).join('')}`);
  try {
    await run(process.execPath, [tailwindCli(root), '-i', input, '-o', output, '--minify'], { cwd: root, capture: true });
  } finally {
    await rm(input, { force: true });
  }
  return readFile(output, 'utf8');
}

/**
 * styles/tailwind.css: Tailwind IntelliSense entry (theme + component classes). Pages never load it.
 * @param {string} root
 * @param {object} config
 * @returns {Promise<string>}
 */
export async function intellisenseCss(root, config) {
  const dir = path.join(root, 'styles');
  const imports = (await componentStylesheets(root)).map((file) => `@import '${relative(dir, file)}';\n`).join('');
  return [
    '/* Managed by aem-kit. Do not edit: regenerated by `npm run aem:init`.\n',
    ` * Tailwind IntelliSense entry only (theme from ${CONFIG_FILE}). Pages never load this file. */\n`,
    "@import 'tailwindcss';\n",
    imports,
    '\n',
    themeBlock(config),
    '\n',
    utilityOverrides(),
    "\n@source '../blocks/**/*.html';\n@source '../drafts/**/*.html';\n",
    imports ? "@source '../components/**/*.html';\n" : '',
  ].join('');
}

/**
 * Rewrites styles/tailwind.css when the component list changed.
 * @param {string} root
 * @param {object} config
 * @returns {Promise<void>}
 */
export async function syncIntellisense(root, config) {
  const file = path.join(root, 'styles', 'tailwind.css');
  const next = await intellisenseCss(root, config);
  const current = await readFile(file, 'utf8').catch(() => null);
  if (current !== null && current !== next) await writeFile(file, next);
}
